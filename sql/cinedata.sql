-- =========================================================
-- 1. TABLA USUARIOS
-- =========================================================

CREATE TABLE usuarios (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY,
    rut VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    apellido VARCHAR2(100) NOT NULL,
    username VARCHAR2(50) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    rol VARCHAR2(20) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'Activo',

    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuarios_rut UNIQUE (rut),
    CONSTRAINT uq_usuarios_username UNIQUE (username),
    CONSTRAINT ck_usuarios_rol
        CHECK (rol IN ('Administrador', 'Cajero')),
    CONSTRAINT ck_usuarios_estado
        CHECK (estado IN ('Activo', 'Inactivo'))
);


-- =========================================================
-- 2. TABLA PELICULAS
-- =========================================================

CREATE TABLE peliculas (
    id_pelicula NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR2(150) NOT NULL,
    director VARCHAR2(100) NOT NULL,
    duracion_min NUMBER(4) NOT NULL,
    genero VARCHAR2(50) NOT NULL,
    clasificacion VARCHAR2(20) NOT NULL,
    sinopsis VARCHAR2(1000) NOT NULL,

    CONSTRAINT pk_peliculas PRIMARY KEY (id_pelicula),
    CONSTRAINT uq_pelicula_director UNIQUE (titulo, director)
);


-- =========================================================
-- 3. TABLA SALAS
-- =========================================================

CREATE TABLE salas (
    id_sala NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre_sala VARCHAR2(50) NOT NULL,
    filas NUMBER(3) NOT NULL,
    columnas NUMBER(3) NOT NULL,
    capacidad_total NUMBER(5) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'Activa',

    CONSTRAINT pk_salas PRIMARY KEY (id_sala),
    CONSTRAINT ck_salas_estado
        CHECK (estado IN ('Activa', 'Inactiva', 'Mantenimiento'))
);


-- =========================================================
-- 4. TABLA ASIENTOS
-- =========================================================

CREATE TABLE asientos (
    id_asiento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_sala NUMBER NOT NULL,
    codigo_asiento VARCHAR2(10) NOT NULL,
    fila_letra CHAR(2) NOT NULL,
    columna_num NUMBER(3) NOT NULL,

    CONSTRAINT pk_asientos PRIMARY KEY (id_asiento),

    CONSTRAINT fk_asientos_sala
        FOREIGN KEY (id_sala)
        REFERENCES salas(id_sala)
        ON DELETE CASCADE,

    CONSTRAINT uq_sala_asiento
        UNIQUE (id_sala, codigo_asiento)
);


-- =========================================================
-- 5. TABLA FUNCIONES
-- =========================================================

CREATE TABLE funciones (
    id_funcion NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pelicula NUMBER NOT NULL,
    id_sala NUMBER NOT NULL,
    fecha DATE NOT NULL,
    hora_inicio TIMESTAMP NOT NULL,
    hora_termino TIMESTAMP NOT NULL,
    idioma VARCHAR2(50) NOT NULL,
    precio_base NUMBER(10,2) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'Programada',

    CONSTRAINT pk_funciones PRIMARY KEY (id_funcion),

    CONSTRAINT fk_funciones_pelicula
        FOREIGN KEY (id_pelicula)
        REFERENCES peliculas(id_pelicula),

    CONSTRAINT fk_funciones_sala
        FOREIGN KEY (id_sala)
        REFERENCES salas(id_sala),

    CONSTRAINT ck_funciones_estado
        CHECK (estado IN (
            'Programada',
            'En Curso',
            'Finalizada',
            'Cancelada'
        ))
);


-- =========================================================
-- 6. TABLA CATEGORIAS
-- =========================================================

CREATE TABLE categorias (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre_categoria VARCHAR2(50) NOT NULL,
    porcentaje_descuento NUMBER(5,2) DEFAULT 0.00,
    estado VARCHAR2(20) DEFAULT 'Activa',

    CONSTRAINT pk_categorias PRIMARY KEY (id_categoria),

    CONSTRAINT uq_categorias_nombre
        UNIQUE (nombre_categoria),

    CONSTRAINT ck_categorias_descuento
        CHECK (porcentaje_descuento >= 0),

    CONSTRAINT ck_categorias_estado
        CHECK (estado IN ('Activa', 'Inactiva'))
);


-- =========================================================
-- 7. TABLA VENTAS
-- =========================================================

CREATE TABLE ventas (
    id_venta NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    fecha_hora_venta TIMESTAMP NOT NULL,
    metodo_pago VARCHAR2(30) NOT NULL,
    monto_total NUMBER(10,2) NOT NULL,
    codigo_comprobante VARCHAR2(100) NOT NULL,
    estado_venta VARCHAR2(20) DEFAULT 'Completada',

    CONSTRAINT pk_ventas PRIMARY KEY (id_venta),

    CONSTRAINT fk_ventas_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario),

    CONSTRAINT uq_ventas_comprobante
        UNIQUE (codigo_comprobante),

    CONSTRAINT ck_ventas_metodo_pago
        CHECK (metodo_pago IN (
            'Efectivo',
            'Tarjeta Débito',
            'Tarjeta Crédito'
        )),

    CONSTRAINT ck_ventas_estado
        CHECK (estado_venta IN (
            'Completada',
            'Anulada'
        ))
);


-- =========================================================
-- 8. TABLA TICKETS POR VENTA
-- =========================================================

CREATE TABLE tickets_venta (
    id_ticket NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_venta NUMBER NOT NULL,
    id_funcion NUMBER NOT NULL,
    id_asiento NUMBER NOT NULL,
    id_categoria NUMBER NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    estado_ticket VARCHAR2(20) DEFAULT 'Vendido',

    CONSTRAINT pk_tickets_venta PRIMARY KEY (id_ticket),

    CONSTRAINT fk_ticket_venta
        FOREIGN KEY (id_venta)
        REFERENCES ventas(id_venta),

    CONSTRAINT fk_ticket_funcion
        FOREIGN KEY (id_funcion)
        REFERENCES funciones(id_funcion),

    CONSTRAINT fk_ticket_asiento
        FOREIGN KEY (id_asiento)
        REFERENCES asientos(id_asiento),

    CONSTRAINT fk_ticket_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id_categoria),

    CONSTRAINT ck_ticket_estado
        CHECK (estado_ticket IN (
            'Vendido',
            'Reservado',
            'Anulado'
        )),

    CONSTRAINT uq_funcion_asiento
        UNIQUE (id_funcion, id_asiento, estado_ticket)
);


-- =========================================================
-- 9. TABLA INFORMES DE VENTAS
-- =========================================================

CREATE TABLE informes_ventas (
    id_informe NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    fecha_inicio_filtro DATE NOT NULL,
    fecha_fin_filtro DATE NOT NULL,
    fecha_hora_generacion TIMESTAMP NOT NULL,
    nombre_archivo VARCHAR2(150) NOT NULL,
    monto_total_recaudado NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_informes_ventas PRIMARY KEY (id_informe),

    CONSTRAINT fk_informes_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario)
);